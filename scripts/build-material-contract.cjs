const path = require('node:path');
const fs = require('node:fs');
const { createHash } = require('node:crypto');
const { buildSync } = require('esbuild');
const yaml = require('js-yaml');
const { skillFiles } = require('../electron/designer-install.cjs');

function parseSkillFrontmatter(markdown) {
  // Keep the newline before the closing delimiter: YAML block scalars use it.
  const match = /^---[ \t]*\r?\n([\s\S]*?\n)---[ \t]*(?:\r?\n|$)/.exec(markdown);
  if (!match) throw new Error('SKILL.md is missing YAML frontmatter');
  const fields = yaml.load(match[1], { schema: yaml.CORE_SCHEMA });
  if (typeof fields?.name !== 'string' || !fields.name.trim() ||
      typeof fields.description !== 'string' || !fields.description.trim()) {
    throw new Error('SKILL.md frontmatter must declare non-empty name and description');
  }
  return fields;
}

function buildEmbeddedSkillModule(root) {
  const raw = skillFiles(path.join(root, 'skills/alex-protoflow-designer'));
  const frontmatter = parseSkillFrontmatter(raw['SKILL.md'].toString('utf8'));
  if (frontmatter.name !== 'alex-protoflow-designer') throw new Error('SKILL.md name must match its directory');
  const ordered = [
    'SKILL.md',
    ...Object.keys(raw)
      .filter((k) => k !== 'SKILL.md')
      .sort(),
  ];
  const entries = ordered.map((relPath) => {
    const buf = raw[relPath];
    const digest = 'sha256:' + createHash('sha256').update(buf).digest('hex');
    return { relPath, text: buf.toString('utf8'), digest, size: buf.length };
  });
  return (
    '// Generated by build-material-contract.cjs.\n' +
    'export const EMBEDDED_SKILL_FRONTMATTER: Record<string, unknown> = JSON.parse(' +
    JSON.stringify(JSON.stringify(frontmatter)) + ');\n' +
    'export const EMBEDDED_SKILL_ENTRIES: readonly { relPath: string; text: string; digest: string; size: number }[] = ' +
    JSON.stringify(entries) +
    ';\n'
  );
}

function buildMaterialContract() {
  const root = path.resolve(__dirname, '..');
  const outfile = path.join(root, 'electron/generated/material-contract.cjs');
  fs.mkdirSync(path.dirname(outfile), { recursive: true });
  buildSync({
    entryPoints: [path.join(root, 'src/proto/registry/nativeContract.ts')],
    outfile, bundle: true, platform: 'node', format: 'cjs', target: 'node22',
    // The packaged MCP has no node_modules. Bundle the parser and metadata too.
    minify: true, legalComments: 'inline',
  });
  const runtime = buildSync({
    entryPoints: [path.join(root, 'src/proto/freeform/frame.tsx')],
    bundle: true, platform: 'browser', format: 'iife', write: false,
    minify: true, define: { 'process.env.NODE_ENV': '"production"' },
  });
  fs.writeFileSync(path.join(root, 'src/proto/freeform/generatedRuntime.ts'),
    '// Generated by build-material-contract.cjs.\nexport const FREEFORM_FRAME_RUNTIME = ' + JSON.stringify(runtime.outputFiles[0].text) + ';\n');
  fs.writeFileSync(path.join(root, 'src/mcp/generatedSkillBundle.ts'), buildEmbeddedSkillModule(root));

  const specMcpOut = path.join(root, 'electron/generated/spec-mcp-server.cjs');
  buildSync({
    entryPoints: [path.join(root, 'src/mcp/cli.ts')],
    outfile: specMcpOut,
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node20',
    minify: true,
    legalComments: 'inline',
  });

  buildSync({
    entryPoints: [path.join(root, 'scripts/client-integrations.cjs')],
    outfile: path.join(root, 'electron/generated/client-integrations.cjs'),
    bundle: true, platform: 'node', format: 'cjs', target: 'node20', minify: true, legalComments: 'inline',
  });

  const pkgMcpOut = path.join(root, 'packages/protoflow-mcp/dist/cli.cjs');
  fs.mkdirSync(path.dirname(pkgMcpOut), { recursive: true });
  fs.writeFileSync(pkgMcpOut, '#!/usr/bin/env node\n' + fs.readFileSync(specMcpOut, 'utf8'));
  fs.chmodSync(pkgMcpOut, 0o755);
}

if (require.main === module) buildMaterialContract();
module.exports = { buildMaterialContract, parseSkillFrontmatter };
