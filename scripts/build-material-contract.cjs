const path = require('node:path');
const fs = require('node:fs');
const { createHash } = require('node:crypto');
const { buildSync } = require('esbuild');
const yaml = require('js-yaml');
const { skillFiles } = require('../electron/designer-install.cjs');

function parseSkillFrontmatter(markdown) {
  // Keep the newline before the closing delimiter: YAML block scalars use it.
  const match = /^---[ \t]*\r?\n([\s\S]*?\n)---[ \t]*(?:\r?\n|$)/.exec(markdown);
  if (!match) throw new Error('SKILL.md is missing YAML frontmatter');
  const fields = yaml.load(match[1], { schema: yaml.CORE_SCHEMA });
  if (typeof fields?.name !== 'string' || !fields.name.trim() ||
      typeof fields.description !== 'string' || !fields.description.trim()) {
    throw new Error('SKILL.md frontmatter must declare non-empty name and description');
  }
  return fields;
}

function computeContractDigestFromPayload(surface) {
  return 'sha256:' + createHash('sha256').update(JSON.stringify(surface)).digest('hex').slice(0, 16);
}

function stampDesignerSkillMarkdown(markdown, serverVersion, contractDigest) {
  const fmMatch = /^(---[ \t]*\r?\n)([\s\S]*?\n)(---[ \t]*(?:\r?\n|$))([\s\S]*)$/.exec(markdown);
  if (!fmMatch) throw new Error('SKILL.md is missing YAML frontmatter');
  const eol = markdown.includes('\r\n') ? '\r\n' : '\n';
  const parsed = parseSkillFrontmatter(markdown);
  const nextFrontmatter = {
    ...parsed,
    metadata: {
      ...(parsed.metadata && typeof parsed.metadata === 'object' && !Array.isArray(parsed.metadata)
        ? parsed.metadata
        : {}),
      serverVersion,
      contractDigest,
    },
  };
  const dumpedHeader = yaml
    .dump(nextFrontmatter, { lineWidth: -1, noRefs: true, quotingType: '"' })
    .replace(/\r?\n/g, eol);

  const rulePattern = /^(1\. \*\*Workspace first\*\*\.[^\r\n]*?`protoflow_workspace\(action="status", expectedContractDigest=")sha256:[0-9a-f]{16}("\)`)/m;
  if (!rulePattern.test(fmMatch[4])) {
    throw new Error('SKILL.md Rule 1 must include the status call with its expectedContractDigest');
  }
  const body = fmMatch[4].replace(rulePattern, (_, prefix, suffix) => prefix + contractDigest + suffix);

  return `---${eol}${dumpedHeader}---${eol}${body.startsWith(eol) ? body : eol + body}`;
}

function evaluateContractDigest(root, serverVersion) {
  const generatedBundlePath = path.join(root, 'src/mcp/generatedSkillBundle.ts');
  if (!fs.existsSync(generatedBundlePath) || !fs.readFileSync(generatedBundlePath, 'utf8').includes('PROTOFLOW_CONTRACT_DIGEST')) {
    fs.mkdirSync(path.dirname(generatedBundlePath), { recursive: true });
    fs.writeFileSync(
      generatedBundlePath,
      [
        '// Bootstrap stub generated by build-material-contract.cjs.',
        `export const PROTOFLOW_SERVER_VERSION = ${JSON.stringify(serverVersion)};`,
        'export const PROTOFLOW_CONTRACT_DIGEST = "sha256:0000000000000000";',
        'export const EMBEDDED_SKILL_FRONTMATTER: Record<string, unknown> = {};',
        'export const EMBEDDED_SKILL_ENTRIES: readonly { relPath: string; text: string; digest: string; size: number }[] = [];',
        '',
      ].join('\n'),
    );
  }
  const bundled = buildSync({
    entryPoints: [path.join(root, 'src/mcp/contractSurface.ts')],
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node20',
    write: false,
  });
  const mod = { exports: {} };
  const fn = new Function('require', 'module', 'exports', bundled.outputFiles[0].text);
  fn(require, mod, mod.exports);
  const surface = mod.exports.buildCanonicalContractSurface();
  return computeContractDigestFromPayload(surface);
}

function buildEmbeddedSkillModule(root, serverVersion, contractDigest) {
  const skillDir = path.join(root, 'skills/alex-protoflow-designer');
  const skillMdPath = path.join(skillDir, 'SKILL.md');
  const currentSkillMd = fs.readFileSync(skillMdPath, 'utf8');
  const stampedSkillMd = stampDesignerSkillMarkdown(currentSkillMd, serverVersion, contractDigest);
  if (stampedSkillMd !== currentSkillMd) {
    fs.writeFileSync(skillMdPath, stampedSkillMd);
  }

  const raw = skillFiles(skillDir);
  const frontmatter = parseSkillFrontmatter(raw['SKILL.md'].toString('utf8'));
  if (frontmatter.name !== 'alex-protoflow-designer') throw new Error('SKILL.md name must match its directory');
  if (frontmatter.metadata?.contractDigest !== contractDigest || frontmatter.metadata?.serverVersion !== serverVersion) {
    throw new Error('SKILL.md frontmatter contract metadata out of sync after stamping');
  }
  const ordered = [
    'SKILL.md',
    ...Object.keys(raw)
      .filter((k) => k !== 'SKILL.md')
      .sort(),
  ];
  const entries = ordered.map((relPath) => {
    const buf = raw[relPath];
    const digest = 'sha256:' + createHash('sha256').update(buf).digest('hex');
    return { relPath, text: buf.toString('utf8'), digest, size: buf.length };
  });
  return (
    '// Generated by build-material-contract.cjs.\n' +
    `export const PROTOFLOW_SERVER_VERSION = ${JSON.stringify(serverVersion)};\n` +
    `export const PROTOFLOW_CONTRACT_DIGEST = ${JSON.stringify(contractDigest)};\n` +
    'export const EMBEDDED_SKILL_FRONTMATTER: Record<string, unknown> = JSON.parse(' +
    JSON.stringify(JSON.stringify(frontmatter)) + ');\n' +
    'export const EMBEDDED_SKILL_ENTRIES: readonly { relPath: string; text: string; digest: string; size: number }[] = ' +
    JSON.stringify(entries) +
    ';\n'
  );
}

function buildMaterialContract() {
  const root = path.resolve(__dirname, '..');
  const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
  const serverVersion = pkg.version;
  if (typeof serverVersion !== 'string' || !serverVersion.trim()) throw new Error('package.json must declare a non-empty version');
  const outfile = path.join(root, 'electron/generated/material-contract.cjs');
  fs.mkdirSync(path.dirname(outfile), { recursive: true });
  buildSync({
    entryPoints: [path.join(root, 'src/proto/registry/nativeContract.ts')],
    outfile, bundle: true, platform: 'node', format: 'cjs', target: 'node22',
    // The packaged MCP has no node_modules. Bundle the parser and metadata too.
    minify: true, legalComments: 'inline',
  });
  const runtime = buildSync({
    entryPoints: [path.join(root, 'src/proto/freeform/frame.tsx')],
    bundle: true, platform: 'browser', format: 'iife', write: false,
    minify: true, define: { 'process.env.NODE_ENV': '"production"' },
  });
  fs.writeFileSync(path.join(root, 'src/proto/freeform/generatedRuntime.ts'),
    '// Generated by build-material-contract.cjs.\nexport const FREEFORM_FRAME_RUNTIME = ' + JSON.stringify(runtime.outputFiles[0].text) + ';\n');

  const contractDigest = evaluateContractDigest(root, serverVersion);
  fs.writeFileSync(
    path.join(root, 'src/mcp/generatedSkillBundle.ts'),
    buildEmbeddedSkillModule(root, serverVersion, contractDigest),
  );

  const specMcpOut = path.join(root, 'electron/generated/spec-mcp-server.cjs');
  buildSync({
    entryPoints: [path.join(root, 'src/mcp/cli.ts')],
    outfile: specMcpOut,
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node20',
    minify: true,
    legalComments: 'inline',
  });

  buildSync({
    entryPoints: [path.join(root, 'scripts/client-integrations.cjs')],
    outfile: path.join(root, 'electron/generated/client-integrations.cjs'),
    bundle: true, platform: 'node', format: 'cjs', target: 'node20', minify: true, legalComments: 'inline',
  });

  const pkgMcpOut = path.join(root, 'packages/protoflow-mcp/dist/cli.cjs');
  fs.mkdirSync(path.dirname(pkgMcpOut), { recursive: true });
  fs.writeFileSync(pkgMcpOut, '#!/usr/bin/env node\n' + fs.readFileSync(specMcpOut, 'utf8'));
  fs.chmodSync(pkgMcpOut, 0o755);
}

if (require.main === module) buildMaterialContract();
module.exports = {
  buildMaterialContract,
  computeContractDigestFromPayload,
  evaluateContractDigest,
  parseSkillFrontmatter,
  stampDesignerSkillMarkdown,
};
