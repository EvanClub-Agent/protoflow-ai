const path = require('node:path');
const fs = require('node:fs');
const { buildSync } = require('esbuild');

function buildMaterialContract() {
  const root = path.resolve(__dirname, '..');
  const outfile = path.join(root, 'electron/generated/material-contract.cjs');
  fs.mkdirSync(path.dirname(outfile), { recursive: true });
  buildSync({
    entryPoints: [path.join(root, 'src/proto/registry/nativeContract.ts')],
    outfile, bundle: true, platform: 'node', format: 'cjs', target: 'node22',
    // The packaged MCP has no node_modules. Bundle the parser and metadata too.
    minify: true, legalComments: 'inline',
  });
  const runtime = buildSync({
    entryPoints: [path.join(root, 'src/proto/freeform/frame.tsx')],
    bundle: true, platform: 'browser', format: 'iife', write: false,
    minify: true, define: { 'process.env.NODE_ENV': '"production"' },
  });
  fs.writeFileSync(path.join(root, 'src/proto/freeform/generatedRuntime.ts'),
    '// Generated by build-material-contract.cjs.\nexport const FREEFORM_FRAME_RUNTIME = ' + JSON.stringify(runtime.outputFiles[0].text) + ';\n');

  const specMcpOut = path.join(root, 'electron/generated/spec-mcp-server.cjs');
  buildSync({
    entryPoints: [path.join(root, 'src/mcp/cli.ts')],
    outfile: specMcpOut,
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node20',
    minify: true,
    legalComments: 'inline',
  });

  buildSync({
    entryPoints: [path.join(root, 'scripts/client-integrations.cjs')],
    outfile: path.join(root, 'electron/generated/client-integrations.cjs'),
    bundle: true, platform: 'node', format: 'cjs', target: 'node20', minify: true, legalComments: 'inline',
  });

  const pkgMcpOut = path.join(root, 'packages/protoflow-mcp/dist/cli.cjs');
  fs.mkdirSync(path.dirname(pkgMcpOut), { recursive: true });
  fs.writeFileSync(pkgMcpOut, '#!/usr/bin/env node\n' + fs.readFileSync(specMcpOut, 'utf8'));
  fs.chmodSync(pkgMcpOut, 0o755);
}

if (require.main === module) buildMaterialContract();
module.exports = { buildMaterialContract };
